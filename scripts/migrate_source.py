#!/usr/bin/env python3
"""Write and validate the canonical YAML source snapshot.

The Python importer still fetches and normalizes W3C/ARRM data. This build-only
step writes the normalized result to YAML, validates it, reads it back, and
optionally regenerates the browser JSON from that YAML.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import sys
import tempfile

import yaml

from source_schema import validate_source

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_YAML = ROOT / 'data' / 'source' / 'role-data.yaml'
HEADER = """# WCAG by Role normalized source snapshot.
# Generated by scripts/migrate_source.py from the production import.
# W3C WCAG 2.2 and ARRM wording/ownership remain authoritative.
# Do not hand-edit source wording or assignments; regenerate and review the diff.
"""


def _atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=path.name + '.', dir=path.parent)
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as handle:
            handle.write(content)
        os.replace(temp_name, path)
    except Exception:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass
        raise


def dump_yaml(data: dict) -> str:
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=1000,
                          default_flow_style=False, indent=2)
    return HEADER + body


def load_yaml(path: Path) -> dict:
    with path.open(encoding='utf-8') as handle:
        return yaml.safe_load(handle)


def load_json(path: Path) -> dict:
    with path.open(encoding='utf-8') as handle:
        return json.load(handle)


def migrate(input_path: Path, yaml_path: Path, json_out: Path | None = None,
            check: bool = False, expected_counts: dict | None = None) -> int:
    data = load_json(input_path)
    if not isinstance(data, dict):
        print('source JSON root must be a mapping', file=sys.stderr)
        return 1
    errors = validate_source(data, expected_counts=expected_counts,
                             require_production=data.get('mode') == 'production')
    if errors:
        for error in errors:
            print(f'source validation error: {error}', file=sys.stderr)
        return 1

    rendered = dump_yaml(data)
    if check:
        if not yaml_path.exists():
            print(f'missing canonical YAML: {yaml_path}', file=sys.stderr)
            return 1
        existing = load_yaml(yaml_path)
        if existing != data:
            print(f'canonical YAML differs from the imported JSON: {yaml_path}', file=sys.stderr)
            return 1
        print(f'YAML snapshot is current: {yaml_path}')
        return 0

    _atomic_write(yaml_path, rendered)
    loaded = load_yaml(yaml_path)
    if loaded != data:
        print('YAML round-trip changed the data; refusing to continue', file=sys.stderr)
        return 1
    errors = validate_source(loaded, expected_counts=expected_counts,
                             require_production=loaded.get('mode') == 'production')
    if errors:
        for error in errors:
            print(f'YAML validation error: {error}', file=sys.stderr)
        return 1
    if json_out is not None:
        _atomic_write(json_out, json.dumps(loaded, indent=2, ensure_ascii=False) + '\n')
    print(f"YAML source: {len(loaded['criteria'])} criteria, {len(loaded['tasks'])} tasks, "
          f"{len(loaded['roles'])} roles -> {yaml_path}")
    if json_out is not None:
        print(f'Browser JSON regenerated from YAML -> {json_out}')
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True,
                        help='Normalized JSON produced by scripts/pipeline.py')
    parser.add_argument('--yaml-out', type=Path, default=DEFAULT_YAML,
                        help='Canonical YAML snapshot path')
    parser.add_argument('--json-out', type=Path,
                        help='Optional browser JSON path regenerated from the YAML')
    parser.add_argument('--check', action='store_true',
                        help='Check that the YAML already matches the input; write nothing')
    parser.add_argument('--expect-criteria', type=int)
    parser.add_argument('--expect-tasks', type=int)
    parser.add_argument('--expect-roles', type=int)
    args = parser.parse_args()
    expected = {}
    for key, value in (('criteria', args.expect_criteria), ('tasks', args.expect_tasks),
                       ('roles', args.expect_roles)):
        if value is not None:
            expected[key] = value
    return migrate(args.input, args.yaml_out, args.json_out, args.check, expected or None)


if __name__ == '__main__':
    raise SystemExit(main())
